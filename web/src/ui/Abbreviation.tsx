const pattern = new RegExp(`(${Object.keys(meanings).sort((a, b) => b.length - a.length).map(escape).join('|')})`, 'gu')

function escape(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

export function abbreviationTitle(value: string): string | undefined {
  const found = [...value.matchAll(pattern)].map((match) => meanings[match[0] as keyof typeof meanings])
  return found.length > 0 ? found.join('; ') : undefined
}

export function AbbreviationText({ text }: { text: string }): ReactNode {
  const parts = text.split(pattern)
  return parts.map((part, index) => {
    const meaning = meanings[part as keyof typeof meanings]
    return meaning ? <abbr key={index} title={meaning}>{part}</abbr> : <Fragment key={index}>{part}</Fragment>
  })
}
